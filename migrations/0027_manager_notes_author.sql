-- Автор приватной заметки руководителя.
--
-- Раньше заметка принадлежала только человеку (person_id), и любой лид
-- скоупа видел заметки всех своих коллег по скоупу. Теперь заметка помнит
-- автора, и обычный лид видит только свои.
--
-- Колонка nullable: существующие заметки автора не имеют, и угадывать его
-- нельзя. Заметка без автора считается общей для лидов скоупа — как было до
-- миграции. Backfill сознательно не делается.
--
-- on delete set null: удаление учётной записи лида не должно уносить его
-- заметки о людях (они принадлежат человеку и остаются), а осиротевшая
-- заметка превращается в «без автора» и снова видна лидам скоупа.
--
-- Индекс на author_user_id не создаём. Запросов «заметки автора» в SQL нет:
-- заметки читаются вместе со снимком рабочего пространства и фильтруются
-- в приложении. Единственный потребитель индекса — проверка FK при удалении
-- пользователя (set null идёт по manager_notes), но пользователи удаляются
-- редко, а таблица маленькая, и seq scan по ней дешевле, чем индекс,
-- который надо поддерживать на каждую запись заметки.
--
-- Ограничение добавляется сразу валидным, без not valid: колонка только что
-- создана и целиком null, проверять нечего, а таблица маленькая.

-- Up Migration
set local lock_timeout = '3s';
set local statement_timeout = '60s';

alter table manager_notes
  add column author_user_id text,
  add constraint manager_notes_author_user_id_fkey
    foreign key (author_user_id) references users(id) on delete set null;

-- Down Migration
-- Теряет авторство: после отката все заметки снова общие для лидов скоупа.
alter table manager_notes drop column author_user_id;
